def _norm(s):
    """Mayúsculas, sin tildes y sin separadores: 'Ki-67'/'KI 67'/'ki67' -> 'KI67'."""
    if not s:
        return ""
    nf = _ud.normalize("NFKD", str(s))
    t = "".join(c for c in nf if not _ud.combining(c)).upper()
    return _re.sub(r"[\s\-_/.]+", "", t)


