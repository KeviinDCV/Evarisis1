_NORM = {}
for _k, _v in ALIAS.items():
    _nk = _norm(_k)
    if _nk and _nk not in _NORM:
        _NORM[_nk] = _v



def resolver(nombre):
    """Columna de BD para ese nombre, o None si no es un biomarcador conocido.

    Primero exacto, luego normalizado (sin tildes, espacios ni guiones).
    """
    if not nombre:
        return None
    col = ALIAS.get(str(nombre).strip().upper()) or _NORM.get(_norm(nombre))
    return _canonico(col) if col else None


def nombres_de(columna):
    """Todos los nombres que resuelven a esa columna (para diagnóstico)."""
    c = _canonico(str(columna or "").upper())
    return sorted(k for k, v in ALIAS.items() if v == c)

